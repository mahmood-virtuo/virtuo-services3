        permit:"For independent work across multiple clients, a Freelance Permit is the standard entry point — fast to set up, no fixed income threshold, and the widest range of approved activities.",
        green:"Once your income and qualifications clear the bar, Green Residence trades a shorter renewal cycle for five years of self-sponsored stability and more flexible family sponsorship.",
        virtual:"If every dollar comes from outside the UAE, a Virtual Work Visa lets you live here without needing a local freelance permit at all — but it isn't a substitute for one if you plan to bill UAE clients."
      };
      var reco=root.querySelector("#vt-reco");
      goals.forEach(function(g){
        g.addEventListener("click", function(){
          var k=g.getAttribute("data-goal");
          goals.forEach(function(x){ x.setAttribute("aria-pressed", x===g?"true":"false"); });
          reco.innerHTML=RECO[k];
          select(k);
        });
      });

      var ZRECO={
        freezone:"<b>Fits</b> a founder, consultant or creative just establishing UAE residency — fast issuance, the widest range of approved activities, and a straightforward path to invoicing your first clients.",
        mohre:"<b>Fits</b> professionals who want a federally recognised freelance permit without a free zone office — paired with a residence permit valid up to two years.",
        gdrfa:"<b>Fits</b> established earners who already meet the income and qualification bar and want a 5-year, self-sponsored residency rather than a 1–2 year renewal cycle."
      };
      var zones=Array.prototype.slice.call(root.querySelectorAll(".vt-zone"));
      var zreco=root.querySelector("#vt-zone-reco");
      zones.forEach(function(z){
        z.addEventListener("click", function(){
          var k=z.getAttribute("data-zone");
          zones.forEach(function(x){ x.setAttribute("aria-pressed", x===z?"true":"false"); });
          if(zreco) zreco.innerHTML=ZRECO[k];
        });
      });

      var SCALE=20000, done=false;
      function fill(){ if(done)return; done=true; root.querySelectorAll(".vt-fill").forEach(function(f){ var lo=+f.getAttribute("data-low"), hi=+f.getAttribute("data-high"); f.style.left=(lo/SCALE*100)+"%"; f.style.width=((hi-lo)/SCALE*100)+"%"; }); }
      var cbo=new IntersectionObserver(function(es){es.forEach(function(e){if(e.isIntersecting){fill();cbo.disconnect();}});},{threshold:.25});
      var cb=root.querySelector(".vt-costbox"); if(cb)cbo.observe(cb);

